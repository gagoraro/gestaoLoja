-- Caixa do dia. "aberto" = TRUE enquanto aberto e NULL depois de fechado:
-- o UNIQUE garante no banco que só existe UM caixa aberto por vez
-- (NULLs não conflitam entre si, funciona em Postgres e H2).
CREATE TABLE caixa (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aberto              BOOLEAN UNIQUE CHECK (aberto IS NULL OR aberto = TRUE),
    valor_abertura      NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (valor_abertura >= 0),
    valor_contado       NUMERIC(12, 2),
    observacao          VARCHAR(500),
    aberto_por          VARCHAR(150),
    fechado_por         VARCHAR(150),
    aberto_em           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fechado_em          TIMESTAMP WITH TIME ZONE
);

CREATE TABLE venda (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caixa_id            BIGINT         NOT NULL REFERENCES caixa (id),
    forma_pagamento     VARCHAR(20)    NOT NULL
                        CHECK (forma_pagamento IN ('DINHEIRO', 'PIX', 'CARTAO_DEBITO', 'CARTAO_CREDITO')),
    valor_total         NUMERIC(12, 2) NOT NULL,
    observacao          VARCHAR(500),
    cancelada           BOOLEAN        NOT NULL DEFAULT FALSE,
    cancelada_em        TIMESTAMP WITH TIME ZONE,
    criado_por          VARCHAR(150),
    criado_em           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_venda_caixa ON venda (caixa_id);

CREATE TABLE venda_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id            BIGINT         NOT NULL REFERENCES venda (id) ON DELETE CASCADE,
    produto_id          BIGINT         NOT NULL REFERENCES produto (id),
    produto_nome        VARCHAR(150)   NOT NULL,
    preco_unitario      NUMERIC(12, 2) NOT NULL,
    quantidade          INTEGER        NOT NULL CHECK (quantidade > 0),
    subtotal            NUMERIC(12, 2) NOT NULL
);

CREATE INDEX idx_venda_item_venda ON venda_item (venda_id);
