-- Schema "loja" (fora do "public") para que as tabelas NÃO fiquem expostas
-- pela Data API (PostgREST) do Supabase. Somente o backend Java acessa.

CREATE TABLE produto (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(50)    NOT NULL UNIQUE,
    nome             VARCHAR(150)   NOT NULL,
    descricao        VARCHAR(1000),
    preco_unitario   NUMERIC(12, 2) NOT NULL CHECK (preco_unitario >= 0),
    quantidade_estoque INTEGER      NOT NULL DEFAULT 0 CHECK (quantidade_estoque >= 0),
    ativo            BOOLEAN        NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE movimentacao_estoque (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id       BIGINT       NOT NULL REFERENCES produto (id),
    tipo             VARCHAR(10)  NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    quantidade       INTEGER      NOT NULL CHECK (quantidade > 0),
    saldo_apos       INTEGER      NOT NULL,
    motivo           VARCHAR(255),
    criado_em        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_mov_produto ON movimentacao_estoque (produto_id, criado_em);

CREATE TABLE orcamento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nome     VARCHAR(150) NOT NULL,
    cliente_contato  VARCHAR(150),
    observacoes      VARCHAR(1000),
    valor_total      NUMERIC(12, 2) NOT NULL DEFAULT 0,
    validade         DATE,
    criado_em        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE orcamento_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orcamento_id     BIGINT         NOT NULL REFERENCES orcamento (id) ON DELETE CASCADE,
    produto_id       BIGINT         NOT NULL REFERENCES produto (id),
    -- snapshot: o orçamento não muda se o produto for editado depois
    produto_nome     VARCHAR(150)   NOT NULL,
    preco_unitario   NUMERIC(12, 2) NOT NULL,
    quantidade       INTEGER        NOT NULL CHECK (quantidade > 0),
    subtotal         NUMERIC(12, 2) NOT NULL
);

CREATE INDEX idx_item_orcamento ON orcamento_item (orcamento_id);
